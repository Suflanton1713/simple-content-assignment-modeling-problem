from __future__ import annotations

import csv
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "benchmarks_organized"
MANIFEST = OUT / "manifest.csv"


SIZES = [
    ("smoke", 6, 8),
    ("small", 12, 12),
    ("medium", 30, 30),
    ("large", 75, 75),
    ("xlarge", 150, 100),
    ("massive", 300, 150),
    ("stress500", 500, 100),
]

DESIGN_SIZES = [
    ("smoke", 6, 8),
    ("small", 12, 12),
    ("medium", 30, 30),
    ("large", 50, 50),
]

BASE_MODELS = (
    "simple_content_assignment.mzn",
    "simple_content_assignment_enhanced.mzn",
    "simple_content_assignment_enhanced_engagement.mzn",
    "simple_content_assignment_epsilon_consensus_free_reducing_conntent.mzn",
)

CONSENSUS_SIZES = [
    ("smoke", 6, 8),
    ("small", 12, 12),
    ("medium", 30, 30),
    ("large", 75, 75),
    ("xlarge", 150, 100),
]


def wrap_array(values: list[int], width: int = 18) -> str:
    chunks = []
    for i in range(0, len(values), width):
        chunks.append(", ".join(str(v) for v in values[i : i + width]))
    if len(chunks) == 1:
        return "[" + chunks[0] + "]"
    return "[\n  " + ",\n  ".join(chunks) + "\n]"


def content_values(c: int, profile: str) -> list[int]:
    if c == 1:
        return [50]

    if profile == "full_spectrum":
        return [round(i * 100 / (c - 1)) for i in range(c)]

    if profile == "center_bridge":
        anchors = [0, 15, 30, 42, 48, 50, 52, 58, 70, 85, 100]
        if c <= len(anchors):
            if c == 2:
                return [0, 100]
            step = (len(anchors) - 1) / (c - 1)
            return [anchors[round(i * step)] for i in range(c)]

        raw = anchors[:]
        for i in range(c - len(anchors)):
            raw.append(max(0, min(100, 50 + round(42 * ((i % 19) - 9) / 9))))
        return [max(0, min(100, v)) for v in raw]

    if profile == "extreme_bridge":
        bands = [0, 5, 10, 20, 35, 45, 50, 55, 65, 80, 90, 95, 100]
        return [bands[i % len(bands)] for i in range(c)]

    raise ValueError(profile)


def initial_opinions(a: int, scenario: str) -> list[int]:
    values = []
    for i in range(a):
        k = i + 1
        if scenario == "balanced_bimodal":
            base = 15 if i % 2 == 0 else 85
            values.append(max(0, min(100, base + ((k * 7) % 15) - 7)))
        elif scenario == "three_clusters":
            cluster = i % 3
            base = [18, 50, 82][cluster]
            values.append(max(0, min(100, base + ((k * 5) % 17) - 8)))
        elif scenario == "high_stubborn":
            base = 10 + ((k * 23) % 81)
            values.append(base)
        elif scenario == "target25_downshift":
            base = 65 + ((k * 11) % 31)
            values.append(min(100, base))
        elif scenario == "target75_upshift":
            base = 5 + ((k * 13) % 36)
            values.append(max(0, base))
        elif scenario in {"anchor20", "anchor20_high_stubborn"}:
            if i == 0:
                values.append(20)
            else:
                base = [25, 55, 85][i % 3] if scenario == "anchor20" else 10 + ((k * 23) % 81)
                values.append(max(0, min(100, base + ((k * 7) % 13) - 6)))
        else:
            raise ValueError(scenario)
    return values


def stubbornness(a: int, scenario: str) -> list[int]:
    values = []
    for i in range(a):
        k = i + 1
        if scenario in {"anchor20", "anchor20_high_stubborn"} and i == 0:
            values.append(100)
        elif scenario in {"high_stubborn", "anchor20_high_stubborn"}:
            values.append(78 + ((k * 7) % 18))
        elif scenario in {"target25_downshift", "target75_upshift"}:
            values.append(35 + ((k * 9) % 45))
        else:
            values.append(25 + ((k * 11) % 60))
    return values


def epsilon_for(scenario: str, iend: int) -> int:
    if scenario == "high_stubborn":
        return 15 if iend >= 30 else 18
    if scenario in {"target25_downshift", "target75_upshift"}:
        return 10 if iend >= 30 else 12
    return 10 if iend >= 30 else 15


def write_dzn(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def fixed_content_lines(
    *,
    title: str,
    a: int,
    iend: int,
    scenario: str,
    profile: str,
    epsilon: int | None = None,
    target: int | None = None,
    min_zero_per_agent: int | None = None,
    min_assign_per_agent: int | None = None,
) -> list[str]:
    c = iend
    lines = [
        f"% {title}",
        "% Generated by tools/generate_benchmark_data.py",
        "% Convention: C = Iend so content availability grows with the horizon.",
        f"A = {a};",
        f"C = {c};",
        f"Iend = {iend};",
    ]
    if epsilon is not None:
        lines.append(f"epsilon = {epsilon};")
    if target is not None:
        lines.append(f"target = {target};")
    if min_zero_per_agent is not None:
        lines.append(f"min_zero_per_agent = {min_zero_per_agent};")
    if min_assign_per_agent is not None:
        lines.append(f"min_assign_per_agent = {min_assign_per_agent};")
    lines.extend(
        [
            "",
            f"initialOpinion = {wrap_array(initial_opinions(a, scenario))};",
            f"stubbornness = {wrap_array(stubbornness(a, scenario))};",
            f"contentValue = {wrap_array(content_values(c, profile))};",
        ]
    )
    return lines


def design_lines(
    *,
    title: str,
    a: int,
    iend: int,
    scenario: str,
    use_target: bool,
    target: int,
    epsilon: int,
) -> list[str]:
    c = iend
    max_assign = max(1, min(c, iend - 2))
    return [
        f"% {title}",
        "% Generated by tools/generate_benchmark_data.py",
        "% For the design model, contentValue is intentionally omitted: the solver designs it.",
        f"A = {a};",
        f"C = {c};",
        f"Iend = {iend};",
        f"epsilon = {epsilon};",
        f"target = {target};",
        f"use_target = {str(use_target).lower()};",
        "min_assign_per_agent = 0;",
        f"max_assign_per_agent = {max_assign};",
        "",
        f"initialOpinion = {wrap_array(initial_opinions(a, scenario))};",
        f"stubbornness = {wrap_array(stubbornness(a, scenario))};",
    ]


def add_manifest(
    rows: list[dict[str, str]],
    *,
    suite: str,
    path: Path,
    size: str,
    a: int,
    iend: int,
    scenario: str,
    models: tuple[str, ...],
    notes: str,
) -> None:
    rows.append(
        {
            "suite": suite,
            "file": str(path.relative_to(ROOT)).replace("\\", "/"),
            "size": size,
            "A": str(a),
            "C": str(iend),
            "Iend": str(iend),
            "scenario": scenario,
            "compatible_models": "|".join(models),
            "notes": notes,
        }
    )


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)

    rows: list[dict[str, str]] = []

    fixed_scenarios = [
        ("balanced_bimodal", "full_spectrum"),
        ("three_clusters", "center_bridge"),
        ("high_stubborn", "extreme_bridge"),
    ]

    for size, a, iend in SIZES:
        for scenario, profile in fixed_scenarios:
            name = f"{size}_{a}a_{iend}i_{scenario}.dzn"
            path = OUT / "base_plain" / name
            write_dzn(
                path,
                fixed_content_lines(
                    title=f"Base/plain benchmark: {size}, {scenario}",
                    a=a,
                    iend=iend,
                    scenario=scenario,
                    profile=profile,
                ),
            )
            add_manifest(
                rows,
                suite="base_plain",
                path=path,
                size=size,
                a=a,
                iend=iend,
                scenario=scenario,
                models=BASE_MODELS,
                notes="No epsilon/target; use with base, enhanced, engagement, and reducing-content models.",
            )

    for size, a, iend in SIZES:
        for scenario, profile in fixed_scenarios:
            epsilon = epsilon_for(scenario, iend)
            name = f"{size}_{a}a_{iend}i_{scenario}_epsilon{epsilon}.dzn"
            path = OUT / "epsilon_free" / name
            write_dzn(
                path,
                fixed_content_lines(
                    title=f"Epsilon free benchmark: {size}, {scenario}",
                    a=a,
                    iend=iend,
                    scenario=scenario,
                    profile=profile,
                    epsilon=epsilon,
                    min_zero_per_agent=7,
                    min_assign_per_agent=1,
                ),
            )
            add_manifest(
                rows,
                suite="epsilon_free",
                path=path,
                size=size,
                a=a,
                iend=iend,
                scenario=scenario,
                models=(
                    "simple_content_assignment_epsilon_consensus.mzn",
                    "simple_content_assignment_epsilon_consensus_free_optimized.mzn",
                ),
                notes="No target; final max_diff must be <= epsilon.",
            )

    directed_scenarios = [
        ("three_clusters", "center_bridge", 50),
        ("target25_downshift", "full_spectrum", 25),
        ("target75_upshift", "full_spectrum", 75),
    ]

    for size, a, iend in SIZES:
        for scenario, profile, target in directed_scenarios:
            epsilon = epsilon_for(scenario, iend)
            name = f"{size}_{a}a_{iend}i_{scenario}_target{target}_epsilon{epsilon}.dzn"
            path = OUT / "epsilon_directed" / name
            write_dzn(
                path,
                fixed_content_lines(
                    title=f"Epsilon directed benchmark: {size}, {scenario}",
                    a=a,
                    iend=iend,
                    scenario=scenario,
                    profile=profile,
                    epsilon=epsilon,
                    target=target,
                    min_zero_per_agent=4,
                    min_assign_per_agent=1,
                ),
            )
            add_manifest(
                rows,
                suite="epsilon_directed",
                path=path,
                size=size,
                a=a,
                iend=iend,
                scenario=scenario,
                models=(
                    "simple_content_assignment_epsilon_consensus_directed.mzn",
                    "simple_content_assignment_epsilon_consensus_directed_optimized.mzn",
                ),
                notes="Directed target band; objective is minimum assigned content.",
            )

    consensus_free_scenarios = [
        ("balanced_bimodal", "full_spectrum"),
        ("three_clusters", "center_bridge"),
        ("high_stubborn", "extreme_bridge"),
    ]

    for size, a, iend in CONSENSUS_SIZES:
        for scenario, profile in consensus_free_scenarios:
            name = f"{size}_{a}a_{iend}i_{scenario}.dzn"
            path = OUT / "consensus_free" / name
            write_dzn(
                path,
                fixed_content_lines(
                    title=f"Consensus free benchmark: {size}, {scenario}",
                    a=a,
                    iend=iend,
                    scenario=scenario,
                    profile=profile,
                    min_zero_per_agent=3,
                    min_assign_per_agent=1,
                ),
            )
            add_manifest(
                rows,
                suite="consensus_free",
                path=path,
                size=size,
                a=a,
                iend=iend,
                scenario=scenario,
                models=("simple_content_assignment_consensus_free.mzn",),
                notes="No epsilon/target; minimizes final polarization max_diff[Iend].",
            )

    consensus_directed_scenarios = [
        ("three_clusters", "center_bridge", 50),
        ("target25_downshift", "full_spectrum", 25),
        ("target75_upshift", "full_spectrum", 75),
    ]

    for size, a, iend in CONSENSUS_SIZES:
        for scenario, profile, target in consensus_directed_scenarios:
            name = f"{size}_{a}a_{iend}i_{scenario}_target{target}.dzn"
            path = OUT / "consensus_directed" / name
            write_dzn(
                path,
                fixed_content_lines(
                    title=f"Consensus directed benchmark: {size}, {scenario}",
                    a=a,
                    iend=iend,
                    scenario=scenario,
                    profile=profile,
                    target=target,
                    min_zero_per_agent=3,
                    min_assign_per_agent=1,
                ),
            )
            add_manifest(
                rows,
                suite="consensus_directed",
                path=path,
                size=size,
                a=a,
                iend=iend,
                scenario=scenario,
                models=("simple_content_assignment_consensus_directed.mzn",),
                notes="Has target but no epsilon; constrains opinion[1,Iend] = target and minimizes final max_diff.",
            )

    for size, a, iend in DESIGN_SIZES:
        for scenario, use_target, target in [
            ("three_clusters", False, 50),
            ("target75_upshift", True, 75),
        ]:
            epsilon = epsilon_for(scenario, iend)
            suite = "design_directed" if use_target else "design_free"
            name = f"{size}_{a}a_{iend}i_{scenario}_target{target}_epsilon{epsilon}.dzn"
            path = OUT / suite / name
            write_dzn(
                path,
                design_lines(
                    title=f"Design benchmark: {size}, {scenario}",
                    a=a,
                    iend=iend,
                    scenario=scenario,
                    use_target=use_target,
                    target=target,
                    epsilon=epsilon,
                ),
            )
            add_manifest(
                rows,
                suite=suite,
                path=path,
                size=size,
                a=a,
                iend=iend,
                scenario=scenario,
                models=("simple_content_design_epsilon_consensus.mzn",),
                notes="contentValue omitted because the design model decides content values.",
            )

    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    with MANIFEST.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(
            fh,
            fieldnames=[
                "suite",
                "file",
                "size",
                "A",
                "C",
                "Iend",
                "scenario",
                "compatible_models",
                "notes",
            ],
        )
        writer.writeheader()
        writer.writerows(rows)

    print(f"Generated {len(rows)} benchmark data files under {OUT}")
    print(f"Manifest: {MANIFEST}")


if __name__ == "__main__":
    main()
